def export_csv(caminho):
    rows = list_jobs()

    with open(caminho, "w", newline="", encoding="utf-8-sig") as f:
        if rows:
            writer = csv.DictWriter(
                f,
                fieldnames=rows[0].keys()
            )
            writer.writeheader()
            writer.writerows(rows)


