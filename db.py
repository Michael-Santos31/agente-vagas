def save_profile(data_dict):
    json_str = json.dumps(data_dict, ensure_ascii=False)

    with conn() as c:
        if USE_POSTGRES:
            execute(
                c,
                """
                INSERT INTO user_profile (id, data_json)
                VALUES (1, ?::jsonb)
                ON CONFLICT (id)
                DO UPDATE SET data_json = EXCLUDED.data_json
                """,
                (json_str,)
            )
        else:
            execute(
                c,
                """
                INSERT OR REPLACE INTO user_profile (id, data_json)
                VALUES (1, ?)
                """,
                (json_str,)
            )


def get_profile():
    with conn() as c:
        res = execute(
            c,
            "SELECT data_json FROM user_profile WHERE id = 1"
        ).fetchone()

        if not res:
            return {}

        data = res["data_json"]

        if isinstance(data, str):
            return json.loads(data)

        return data


