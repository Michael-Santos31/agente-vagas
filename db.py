def url_known(url):
    url = normalize_url(url)

    with conn() as c:
        res = execute(
            c,
            "SELECT id FROM jobs WHERE url = ?",
            (url,)
        ).fetchone()

        return res is not None


def save_job(**campos):
    if "url" not in campos or not campos["url"]:
        raise ValueError("A vaga precisa ter uma URL.")

    campos["url"] = normalize_url(campos["url"])

    if not campos.get("found_at"):
        campos["found_at"] = agora()

    campos["updated_at"] = agora()

    colunas = ", ".join(campos.keys())
    placeholders = ", ".join(["?"] * len(campos))

    if USE_POSTGRES:
        sql = (
            f"INSERT INTO jobs ({colunas}) "
            f"VALUES ({placeholders}) "
            "ON CONFLICT (url) DO NOTHING"
        )
    else:
        sql = (
            f"INSERT OR IGNORE INTO jobs ({colunas}) "
            f"VALUES ({placeholders})"
        )

    with conn() as c:
        execute(c, sql, tuple(campos.values()))


def set_status(job_id, status):
    with conn() as c:
        execute(
            c,
            "UPDATE jobs SET status = ?, updated_at = ? WHERE id = ?",
            (status, agora(), job_id)
        )


def set_notes(job_id, texto):
    with conn() as c:
        execute(
            c,
            "UPDATE jobs SET notes = ?, updated_at = ? WHERE id = ?",
            (texto, agora(), job_id)
        )


def list_jobs():
    with conn() as c:
        res = execute(
            c,
            """
            SELECT * FROM jobs
            ORDER BY
                CASE WHEN status = 'descartada' THEN 1 ELSE 0 END,
                score DESC,
                found_at DESC
            """
        ).fetchall()

        return [dict(row) for row in res]


def counts():
    with conn() as c:
        res = execute(
            c,
            "SELECT status, COUNT(*) AS qtd FROM jobs GROUP BY status"
        ).fetchall()

        total = execute(
            c,
            "SELECT COUNT(*) AS total FROM jobs"
        ).fetchone()["total"]

        resultado = {
            row["status"]: row["qtd"]
            for row in res
        }

        resultado["total"] = total
        return resultado


