def add_source(name, url, js=False):
    url = normalize_url(url)

    with conn() as c:
        if USE_POSTGRES:
            sql = """
                INSERT INTO sources (name, url, js)
                VALUES (?, ?, ?)
                ON CONFLICT (url) DO NOTHING
            """
        else:
            sql = """
                INSERT OR IGNORE INTO sources (name, url, js)
                VALUES (?, ?, ?)
            """

        execute(c, sql, (name, url, 1 if js else 0))


def remove_source(source_id):
    with conn() as c:
        execute(
            c,
            "DELETE FROM sources WHERE id = ?",
            (source_id,)
        )


def list_sources():
    with conn() as c:
        res = execute(
            c,
            "SELECT * FROM sources ORDER BY id"
        ).fetchall()

        return [dict(row) for row in res]


def touch_source(source_id):
    with conn() as c:
        execute(
            c,
            "UPDATE sources SET last_run = ? WHERE id = ?",
            (agora(), source_id)
        )


